#!/bin/sh
# mkcrl.sh — the CRLs the revocation vectors hand to validator/p3-verify.
#
# The verifier never fetches revocation material: a CRL is an input the person
# running it chooses to supply (`--revocation FILE`). These files are that
# input, and they are built here so the fixtures are reproducible rather than
# pasted into the tree.
#
# THROWAWAY TEST MATERIAL. Nothing here is secret, nothing here is trusted by
# anyone, and none of it may be used for any purpose except testing the
# verifier. The keys and certificates come from tools/mkpki.sh (vectors/pki).
#
# Runnable offline. Needs only the `openssl` binary.
#
#   sh tools/mkcrl.sh                 # rebuild vectors/pki/crl-*
#   sh tools/mkcrl.sh /some/other/pki # rebuild the CRLs of another PKI built
#                                     # by mkpki.sh (tools/mkpki.sh calls this)
#   ADD=delta sh tools/mkcrl.sh [pki] # build ONLY the delta CRL, touching nothing
#                                     # else — how it was added to the shipped tree
#                                     # without re-signing the shipped crl-* files
#                                     # (an ECDSA signature differs on every run, so
#                                     # a full rerun moves every existing digest)
#
# The DATES are fixed, so "expired" is expired on any host at any time, exactly
# as the certificate dates are. The CRL bytes still change whenever the PKI is
# regenerated, because the CA's key signs them — rebuild the containers then too
# (tools/mkasic.py / tools/mk3.sh), as mkpki.sh's header says.

set -eu
LC_ALL=C
export LC_ALL

here=$(cd -- "$(dirname -- "$0")" && pwd)
repo=$(cd -- "$here/.." && pwd)

pki=${1:-$repo/vectors/pki}
[ -d "$pki" ] || { printf 'mkcrl.sh: %s is not a directory\n' "$pki" >&2; exit 1; }
pki=$(cd -- "$pki" && pwd)

OPENSSL=${OPENSSL:-openssl}
command -v "$OPENSSL" >/dev/null 2>&1 || { printf 'mkcrl.sh: no %s on PATH\n' "$OPENSSL" >&2; exit 1; }

# the same fixed windows tools/mkpki.sh issues certificates with
NB_VALID=20200101000000Z
NA_VALID=20990101000000Z
NA_EXPIRED=20210101000000Z

for f in intermediateA rootA rootB; do
	[ -f "$pki/$f.crt.pem" ] && [ -f "$pki/$f.key.pem" ] || {
		printf 'mkcrl.sh: %s/%s.{crt,key}.pem missing — run tools/mkpki.sh first\n' "$pki" "$f" >&2
		exit 1
	}
done

# a CA database that signs a CRL and issues nothing: mkpki.sh signs certificates
# with `openssl x509 -req`, so there is no issued-certificate index to inherit
# and the entries below are written by hand, from the certificates themselves.
cnf() { # $1: CA basename
	cat >"$pki/ca-$1.cnf" <<EOF
# the CRL-signing database for $1. Regenerated by tools/mkcrl.sh; not a system
# configuration, and no certificate is ever issued through it.
[ ca ]
default_ca = CA_default
[ CA_default ]
dir               = $pki
database          = $pki/ca-$1.index
crlnumber         = $pki/ca-$1.crlnumber
private_key       = $pki/$1.key.pem
certificate       = $pki/$1.crt.pem
default_md        = sha256
default_crl_days  = 3650
policy            = policy_any
[ policy_any ]
commonName = optional
[ crl_ext ]
authorityKeyIdentifier = keyid:always
[ crl_ext_delta ]
authorityKeyIdentifier = keyid:always
# the deltaCRLIndicator (2.5.29.27), by raw OID with an explicit DER value:
# INTEGER 2. The friendly names ('deltaCRLIndicator', 'delta_crl_indicator') do
# not exist in this openssl's extension table and a bare '2.5.29.27 = critical,
# 2' is refused (MEASURED, 3.5.3); only OID + DER: works.
2.5.29.27 = critical,DER:02:01:02
EOF
	: >"$pki/ca-$1.index"
	printf '1000\n' >"$pki/ca-$1.crlnumber"
}

gencrl() { # $1: CA basename, $2: output basename, $3: thisUpdate, $4: nextUpdate, $5: crlexts section (default crl_ext)
	"$OPENSSL" ca -config "$pki/ca-$1.cnf" -gencrl \
		-crl_lastupdate "$3" -crl_nextupdate "$4" -crlexts "${5:-crl_ext}" \
		-out "$pki/$2" 2>/dev/null
}

# ADD=delta rebuilds ONLY the delta CRL, against an existing PKI: every other
# CRL is re-signed by the full run below and an ECDSA signature differs on
# every run, so a full rerun moves the digest of every shipped crl-*.
if [ "${ADD:-}" = delta ]; then
	cnf intermediateA
	gencrl intermediateA crl-intermediateA-delta.pem "$NB_VALID" "$NA_VALID" crl_ext_delta
	rm -f "$pki"/ca-*.cnf "$pki"/ca-*.index "$pki"/ca-*.crlnumber "$pki"/ca-*.crlnumber.old
	chmod 644 "$pki"/crl-*.pem
	printf 'mkcrl.sh: ADD=delta built %s/crl-intermediateA-delta.pem\n' "$pki"
	"$OPENSSL" crl -in "$pki/crl-intermediateA-delta.pem" -noout -text | sed -n '/Delta CRL Indicator/,+1p'
	exit 0
fi
[ -z "${ADD:-}" ] || { printf 'mkcrl.sh: unknown ADD=%s (delta is the only add-on)\n' "$ADD" >&2; exit 1; }

# intermediateA — the CA that issued the sealer (signerA, serial 0x0A11)
cnf intermediateA
# a CRL that says nothing about anyone: the "checked clean" arm
gencrl intermediateA crl-intermediateA-clean.pem "$NB_VALID" "$NA_VALID"
# the same CRL with ONE entry: signerA revoked. One line here, one entry there —
# the index line is written by hand because no certificate is issued through
# this database.
printf 'R\t20990101000000Z\t210601120000Z,keyCompromise\t0A11\tunknown\t/CN=Witness AG/O=martelage test PKI (throwaway)\n' \
	>"$pki/ca-intermediateA.index"
gencrl intermediateA crl-intermediateA-revoked.pem "$NB_VALID" "$NA_VALID"
: >"$pki/ca-intermediateA.index"
# EXPIRED: nextUpdate in 2021, so it is expired on every host, forever
gencrl intermediateA crl-intermediateA-expired.pem "$NB_VALID" "$NA_EXPIRED"
: >"$pki/ca-intermediateA.index"

# DELTA: the same CA, carrying a critical deltaCRLIndicator (2.5.29.27) — a
# statement ABOUT another CRL, never a full one. It exists to be REFUSED by
# tools/p3-fetch: the verifier has no delta handling (MEASURED, zero delta code
# in validator/p3-verify) and would read it as an empty FULL CRL, manufacturing
# a false 'clean'. Never hand it to the verifier; serve it from the rig to test
# the refusal. Index empty: a delta's entries live in the base CRL it points at
gencrl intermediateA crl-intermediateA-delta.pem "$NB_VALID" "$NA_VALID" crl_ext_delta
: >"$pki/ca-intermediateA.index"

# rootA — the anchor under which intermediateA was issued, so a CRL from it is
# what speaks for the intermediate in the chain
cnf rootA
gencrl rootA crl-rootA-clean.pem "$NB_VALID" "$NA_VALID"

# rootB — a CA that issued nothing in the vectors' chain. Its CRL is perfectly
# valid and speaks for none of that chain: the "wrong issuer" arm
cnf rootB
gencrl rootB crl-rootB-clean.pem "$NB_VALID" "$NA_VALID"

# the verifier takes PEM or DER; one of the arms hands it the DER form of a CRL
# it otherwise passes the PEM form of
"$OPENSSL" crl -in "$pki/crl-intermediateA-clean.pem" -outform DER -out "$pki/crl-intermediateA-clean.der"

# the CA databases and their config are scaffolding, not fixtures: a vector
# directory holds the material a verifier is handed and the text about it, so
# these are removed rather than shipped
rm -f "$pki"/ca-*.cnf "$pki"/ca-*.index "$pki"/ca-*.crlnumber "$pki"/ca-*.crlnumber.old

chmod 644 "$pki"/crl-*.pem "$pki"/crl-*.der

printf 'mkcrl.sh: built the CRLs under %s\n' "$pki"
for f in intermediateA-clean intermediateA-revoked intermediateA-expired intermediateA-delta rootA-clean rootB-clean; do
	printf '  %-22s %s\n' "$f" \
		"$("$OPENSSL" crl -in "$pki/crl-$f.pem" -noout -issuer -nextupdate | tr '\n' ' ' | sed 's/  */ /g')"
done
