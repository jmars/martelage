#!/bin/sh
# mkpki.sh — build the THROWAWAY test PKI the P3 vectors use.
#
# Nothing here is secret, nothing here is trusted by anyone, and none of these
# keys or certificates may be used for any purpose other than testing
# validator/p3-verify. See vectors/pki/README.md.
#
# Runnable offline. Needs only the `openssl` binary (3.5 or later, for
# `openssl x509 -not_before/-not_after`).
#
# The DATES are fixed and the layout is fixed, so the verdicts the vectors
# assert are reproducible on any host at any time; the key material is freshly
# generated on each run, so the certificate bytes differ between runs and the
# shipped containers must be rebuilt with tools/mkasic.py if you regenerate.
#
#   sh tools/mkpki.sh          # rebuild vectors/pki in place

set -eu
LC_ALL=C
export LC_ALL

here=$(cd -- "$(dirname -- "$0")" && pwd)
repo=$(cd -- "$here/.." && pwd)
pki="$repo/vectors/pki"

OPENSSL=${OPENSSL:-openssl}
command -v "$OPENSSL" >/dev/null 2>&1 || { printf 'mkpki.sh: no %s on PATH\n' "$OPENSSL" >&2; exit 1; }

# every certificate carries a validity window that does not depend on the clock,
# so an "expired" certificate is expired forever and a "valid" one stays valid.
NB_VALID=20200101000000Z
NA_VALID=20990101000000Z
NB_EXPIRED=20200101000000Z
NA_EXPIRED=20210101000000Z

# remove the GENERATED material only: the README beside it is documentation and
# a rebuild that silently deleted it would be a rebuild that lost the tree's own
# account of what the keys are
rm -rf "$pki/anchors" "$pki/anchors-b"
rm -f "$pki"/*.crt.pem "$pki"/*.key.pem "$pki"/*.csr "$pki"/*.cnf "$pki"/*.serial
mkdir -p "$pki/anchors" "$pki/anchors-b"

cat >"$pki/openssl.cnf" <<'EOF'
# the extensions every certificate in the test PKI is issued with.
# Regenerated by tools/mkpki.sh; not a system configuration.
[ req ]
distinguished_name = req_dn
prompt             = no
[ req_dn ]
CN = placeholder
[ v3_root ]
basicConstraints       = critical,CA:TRUE
keyUsage               = critical,keyCertSign,cRLSign
subjectKeyIdentifier   = hash
[ v3_intermediate ]
basicConstraints       = critical,CA:TRUE,pathlen:0
keyUsage               = critical,keyCertSign,cRLSign
subjectKeyIdentifier   = hash
[ v3_sealer ]
basicConstraints       = critical,CA:FALSE
keyUsage               = critical,digitalSignature,nonRepudiation
subjectKeyIdentifier   = hash
authorityKeyIdentifier = keyid
[ v3_tsa ]
basicConstraints       = critical,CA:FALSE
keyUsage               = critical,digitalSignature
extendedKeyUsage       = critical,timeStamping
subjectKeyIdentifier   = hash
authorityKeyIdentifier = keyid
EOF
cnf="$pki/openssl.cnf"

key() { # $1: basename
	"$OPENSSL" ecparam -name prime256v1 -genkey -noout -out "$pki/$1.key.pem" 2>/dev/null
}
root() { # $1: basename, $2: CN, $3: serial
	key "$1"
	"$OPENSSL" req -new -x509 -key "$pki/$1.key.pem" -sha256 -set_serial "$3" \
		-not_before "$NB_VALID" -not_after "$NA_VALID" \
		-subj "/CN=$2/O=martelage test PKI (throwaway)" \
		-config "$cnf" -extensions v3_root -out "$pki/$1.crt.pem" 2>/dev/null
}
leaf() { # $1: basename, $2: CN, $3: serial, $4: issuer basename, $5: ext section, $6: notBefore, $7: notAfter
	key "$1"
	"$OPENSSL" req -new -key "$pki/$1.key.pem" -subj "/CN=$2/O=martelage test PKI (throwaway)" \
		-config "$cnf" -out "$pki/$1.csr" 2>/dev/null
	"$OPENSSL" x509 -req -in "$pki/$1.csr" -CA "$pki/$4.crt.pem" -CAkey "$pki/$4.key.pem" \
		-set_serial "$3" -sha256 -not_before "$6" -not_after "$7" \
		-extfile "$cnf" -extensions "$5" -out "$pki/$1.crt.pem" 2>/dev/null
	rm -f "$pki/$1.csr"
}
# a second certificate for an EXISTING key pair: same subject, same public key,
# a different validity window. One axis, one difference — a container signed with
# the valid certificate and the same container signed with the expired one differ
# in the certificate's dates and in nothing else.
rekey() { # $1: key basename to reuse, $2: output basename, $3: CN, $4: serial, $5: issuer, $6: ext, $7: nb, $8: na
	"$OPENSSL" req -new -key "$pki/$1.key.pem" -subj "/CN=$3/O=martelage test PKI (throwaway)" \
		-config "$cnf" -out "$pki/$2.csr" 2>/dev/null
	"$OPENSSL" x509 -req -in "$pki/$2.csr" -CA "$pki/$5.crt.pem" -CAkey "$pki/$5.key.pem" \
		-set_serial "$4" -sha256 -not_before "$7" -not_after "$8" \
		-extfile "$cnf" -extensions "$6" -out "$pki/$2.crt.pem" 2>/dev/null
	rm -f "$pki/$2.csr"
}

# two roots: A is the anchor the vectors supply, B is the anchor they withhold
# until the arm that supplies it. One axis, one difference.
root rootA "martelage test root A" 0x0A01
root rootB "martelage test root B" 0x0B01

# an intermediate, so the chain a verifier has to build is not one hop
leaf intermediateA "martelage test intermediate A" 0x0A02 rootA v3_intermediate "$NB_VALID" "$NA_VALID"
# the SAME intermediate key and subject, expired in 2021: the chain-date arm. A
# signer issued by the valid intermediate and the same signer carrying this one
# differ in the intermediate's window and in nothing else.
rekey intermediateA intermediateA-expired "martelage test intermediate A" 0x0A03 rootA v3_intermediate \
	"$NB_EXPIRED" "$NA_EXPIRED"

# the sealer: a legal person OTHER than the operator
leaf signerA "Witness AG" 0x0A11 intermediateA v3_sealer "$NB_VALID" "$NA_VALID"
# a sealer under the root the vectors withhold
leaf signerB "Witness BV" 0x0B11 rootB v3_sealer "$NB_VALID" "$NA_VALID"
# a sealer whose certificate expired in 2021: the date arm of §9.3
leaf expired "Retired Witness AG" 0x0A12 intermediateA v3_sealer "$NB_EXPIRED" "$NA_EXPIRED"

# the operator's own key pair: the party a self-seal cannot defend against
leaf operator "Operator GmbH" 0x0A13 intermediateA v3_sealer "$NB_VALID" "$NA_VALID"

# a SECOND sealer under the same intermediate: the control for the multi-signer
# arm. Two signers, neither of them the operator, must still pass.
leaf signerC "Witness C GmbH" 0x0A14 intermediateA v3_sealer "$NB_VALID" "$NA_VALID"

# the timestamping authority
leaf tsa "martelage test TSA" 0x0A21 rootA v3_tsa "$NB_VALID" "$NA_VALID"
# the same TSA key and subject, expired in 2021: a token from a certificate that
# was not valid when it stamped establishes no time this run may rely on
rekey tsa tsa-expired "martelage test TSA" 0x0A22 rootA v3_tsa "$NB_EXPIRED" "$NA_EXPIRED"

# the verifier's trust anchor directories. anchors-b holds rootA as well, so the
# one container it decides (signed under rootB) can also get its timestamp
# checked; the difference between the two directories is rootB and nothing else.
cp "$pki/rootA.crt.pem" "$pki/anchors/rootA.crt.pem"
cp "$pki/rootA.crt.pem" "$pki/anchors-b/rootA.crt.pem"
cp "$pki/rootB.crt.pem" "$pki/anchors-b/rootB.crt.pem"

# the TSA's configuration. openssl ts -reply reads a serial file and appends;
# the relative paths are resolved against the working directory, which is why
# tools/mkasic.py runs openssl with vectors/pki as its cwd.
cat >"$pki/tsa.cnf" <<'EOF'
# the test timestamping authority's configuration. Throwaway test material.
[ tsa ]
default_tsa = tsa_config
[ tsa_config ]
dir               = .
serial            = tsa.serial
crypto_device     = builtin
signer_cert       = tsa.crt.pem
certs             = rootA.crt.pem
signer_key        = tsa.key.pem
signer_digest     = sha256
default_policy    = 1.3.6.1.4.1.99999.1
other_policies    = 1.3.6.1.4.1.99999.1
digests           = sha256, sha384, sha512
accuracy          = secs:1
ordering          = yes
tsa_name          = yes
ess_cert_id_chain = yes
ess_cert_id_alg   = sha256
EOF
printf '01\n' >"$pki/tsa.serial"

# the expired TSA's own configuration: the same file, one certificate and one
# serial file different, so a token stamped with it differs by the TSA's dates
sed -e 's/^serial .*/serial            = tsa-expired.serial/' \
	-e 's/^signer_cert .*/signer_cert       = tsa-expired.crt.pem/' \
	"$pki/tsa.cnf" >"$pki/tsa-expired.cnf"
printf '01\n' >"$pki/tsa-expired.serial"

chmod 644 "$pki"/*.crt.pem "$pki"/*.key.pem "$pki"/*.cnf "$pki"/*.serial "$pki"/anchors/*.crt.pem "$pki"/anchors-b/*.crt.pem

printf 'mkpki.sh: built %s\n' "$pki"
for f in rootA intermediateA intermediateA-expired signerA signerC signerB expired operator tsa tsa-expired rootB; do
	printf '  %-14s %s\n' "$f" "$("$OPENSSL" x509 -in "$pki/$f.crt.pem" -noout -subject -issuer -dates -dateopt iso_8601 2>/dev/null | tr '\n' ' ' | sed 's/  */ /g')"
done
