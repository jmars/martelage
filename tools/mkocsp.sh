#!/bin/sh
# mkocsp.sh — the OCSP responses the OCSP vectors hand to validator/p3-verify.
#
# The verifier never fetches revocation material and never contacts a responder:
# an OCSP response is an input the person running it chooses to supply
# (`--ocsp-response FILE`, or a file in a `--revocation-dir DIR`). These files are
# that input, and they are built here so the fixtures are reproducible rather than
# pasted into the tree.
#
# THROWAWAY TEST MATERIAL. Nothing here is secret, nothing here is trusted by
# anyone, and none of it may be used for any purpose except testing the
# verifier. The keys and certificates come from tools/mkpki.sh.
#
# Runnable offline. Needs only the `openssl` binary and `python3` (for the
# re-dating step below). No port is opened, no URL is read: every response is
# produced from a request FILE with `openssl ocsp -index ... -reqin ...`.
#
#   sh tools/mkocsp.sh                 # rebuild vectors/pki/ocsp-*
#   sh tools/mkocsp.sh /some/other/pki # another PKI built by tools/mkpki.sh
#
# WHY THE RESPONSES ARE RE-DATED. `openssl ocsp` timestamps a response with the
# build second: thisUpdate is `now`, nextUpdate is `now + -ndays/-nmin`. Two
# consequences, both measured on openssl 3.5.3:
#   * a response generated today can never be expired tomorrow, so an "expired
#     response" fixture would be a fixture with a documented time dependency —
#     exactly what the CRLs avoid by fixing their dates (tools/mkcrl.sh);
#   * `-ndays`/`-nmin` refuse a non-positive value ("Non-positive number"), so
#     the window cannot be moved backwards from the command line at all.
# So every response here is generated by the responder and then its window (and
# Produced At) is moved to the SAME fixed dates the certificates and CRLs use —
# 2020-01-01 for thisUpdate, 2099-01-01 for nextUpdate — and the moved
# tbsResponseData is re-signed with the same responder key (`openssl dgst
# -sha256 -sign`). The expired arm gets nextUpdate 2021-01-01 instead, so it is
# expired on any host at any time. The bytes still change whenever the PKI is
# regenerated, because the responder's key signs them.

set -eu
LC_ALL=C
export LC_ALL

here=$(cd -- "$(dirname -- "$0")" && pwd)
repo=$(cd -- "$here/.." && pwd)

pki=${1:-$repo/vectors/pki}
[ -d "$pki" ] || { printf 'mkocsp.sh: %s is not a directory\n' "$pki" >&2; exit 1; }
pki=$(cd -- "$pki" && pwd)

OPENSSL=${OPENSSL:-openssl}
command -v "$OPENSSL" >/dev/null 2>&1 || { printf 'mkocsp.sh: no %s on PATH\n' "$OPENSSL" >&2; exit 1; }
command -v python3 >/dev/null 2>&1 || { printf 'mkocsp.sh: no python3 on PATH\n' >&2; exit 1; }

# the responder certificates are PKI material and are built by tools/mkpki.sh.
# A missing one is an error here, not something to invent: a response signed by a
# key the tree does not hold is a fixture nobody can rebuild.
for f in intermediateA signerA signerC; do
	[ -f "$pki/$f.crt.pem" ] || {
		printf 'mkocsp.sh: %s/%s.crt.pem missing — run tools/mkpki.sh first\n' "$pki" "$f" >&2
		exit 1
	}
done
# ocsp-responder: the DELEGATED responder, issued by intermediate A (so its chain
# reaches root A, the anchor the vectors supply). ocsp-rogue: a SELF-SIGNED
# responder, which chains to nothing.
for f in ocsp-responder ocsp-rogue; do
	[ -f "$pki/$f.crt.pem" ] && [ -f "$pki/$f.key.pem" ] || {
		printf 'mkocsp.sh: %s/%s.{crt,key}.pem missing — run tools/mkpki.sh first\n' "$pki" "$f" >&2
		exit 1
	}
done

# the fixed windows every shipped response carries (see the header)
NB_2020=20200101000000Z
NA_2099=20990101000000Z
NA_2021=20210101000000Z

work=$(mktemp -d "${TMPDIR:-/tmp}/mkocsp.XXXXXX")
trap 'rm -rf "$work"' EXIT HUP INT TERM

# the CA database `openssl ocsp -index` reads. One line per certificate:
# status, expiry, revocation time+reason (revoked only), serial, name, subject.
# The subject lines are copied from the certificates themselves so they cannot
# drift from what the certificates say.
subject() { "$OPENSSL" x509 -in "$pki/$1.crt.pem" -noout -subject -nameopt oneline,-space_eq |
	sed -e 's/^subject=//' -e 's/, /\\, /g'; }

index() { # $1: output file, $2: status letter, $3: cert basename, $4: serial
	line="$2	$NA_2099		$4	unknown	$(subject "$3")"
	[ "$2" = "R" ] && line="R	$NA_2099	210601120000Z,keyCompromise	$4	unknown	$(subject "$3")"
	printf '%s\n' "$line" >"$1"
}

request() { # $1: output request file, $2: cert basename
	"$OPENSSL" ocsp -issuer "$pki/intermediateA.crt.pem" -cert "$pki/$2.crt.pem" \
		-no_nonce -reqout "$1" 2>/dev/null
}

respond() { # $1: index, $2: request, $3: responder basename, $4: output DER
	"$OPENSSL" ocsp -index "$1" -rsigner "$pki/$3.crt.pem" -rkey "$pki/$3.key.pem" \
		-CA "$pki/intermediateA.crt.pem" -reqin "$2" -respout "$4" -ndays 3000 2>/dev/null
}

# ── the dates, and nothing else, are moved after the responder has signed ─────
# A GeneralizedTime in a DER OCSP response is 15 bytes of ASCII; the two fields
# that matter are thisUpdate and nextUpdate (and, optionally, Produced At). The
# re-dating below replaces those bytes, re-signs the tbsResponseData with the
# same responder key, and re-wraps the response — so the result is a response the
# responder key genuinely signed, carrying the fixed window.
redate() { # $1: in DER, $2: out DER, $3: responder key, $4: thisUpdate, $5: nextUpdate, $6: producedAt or "" 
	python3 - "$1" "$2" "$pki/$3.key.pem" "$OPENSSL" "$4" "$5" "$6" <<'PY'
import os, subprocess, sys, tempfile

def read_tlv(buf, off):
    tag = buf[off]; off += 1
    length = buf[off]; off += 1
    if length & 0x80:
        n = length & 0x7F
        length = int.from_bytes(buf[off:off + n], "big"); off += n
    return tag, off, length

def tlv(buf, off):
    tag, content_start, length = read_tlv(buf, off)
    return tag, off, content_start, length

def children(buf, start, length):
    off, end, out = start, start + length, []
    while off < end:
        tag, head, content_start, length = tlv(buf, off)
        out.append((tag, head, content_start, length))
        off = content_start + length
    return out

def wrap(tag, content):
    n = len(content)
    if n < 0x80:
        return bytes([tag, n]) + content
    nb = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([tag, 0x80 | len(nb)]) + nb + content

src, dst, key, openssl, thisupdate, nextupdate, produced = sys.argv[1:8]
buf = open(src, "rb").read()
_outer_tag, _outer_head, outer_content, outer_length = tlv(buf, 0)
top = children(buf, outer_content, outer_length)
enum_tlv = buf[top[0][1]:top[0][2] + top[0][3]]
ctx = top[1]
response_bytes = children(buf, ctx[2], ctx[3])[0]
rb_children = children(buf, response_bytes[2], response_bytes[3])
oid_tlv = buf[rb_children[0][1]:rb_children[0][2] + rb_children[0][3]]
octet = rb_children[1]
basic = buf[octet[2]:octet[2] + octet[3]]
_basic_tag, _basic_head, basic_content, basic_length = tlv(basic, 0)
basic_children = children(basic, basic_content, basic_length)
tbs = basic_children[0]
tbs_bytes = bytearray(basic[tbs[1]:tbs[2] + tbs[3]])
algid_tlv = basic[basic_children[1][1]:basic_children[1][2] + basic_children[1][3]]
certs_tlv = b"".join(basic[c[1]:c[2] + c[3]] for c in basic_children[3:])

def put(element, value):
    """replace one GeneralizedTime's 15 ASCII bytes, TLV header untouched"""
    value = value.encode() if isinstance(value, str) else value
    start, length = element[2] - tbs[1], element[3]
    assert length == 15, "a GeneralizedTime that is not 15 bytes: %r" % length
    tbs_bytes[start:start + length] = value

moved = 0
for child in children(basic, tbs[2], tbs[3]):
    if child[0] == 0x18:                      # Produced At, a direct child of tbs
        if produced:
            put(child, produced)
            moved += 1
    elif child[0] == 0x30:                    # the SEQUENCE OF SingleResponse
        for single in children(basic, child[2], child[3]):
            for field in children(basic, single[2], single[3]):
                if field[0] == 0x18:          # thisUpdate
                    put(field, thisupdate)
                    moved += 1
                elif field[0] == 0xA0:        # [0] EXPLICIT nextUpdate
                    inner = children(basic, field[2], field[3])[0]
                    assert inner[0] == 0x18
                    put(inner, nextupdate)
                    moved += 1
assert moved >= 2, "expected thisUpdate and nextUpdate, moved %d field(s)" % moved

tmp = tempfile.mkdtemp(prefix="mkocsp.")
tbs_path, sig_path = os.path.join(tmp, "tbs.der"), os.path.join(tmp, "sig.bin")
open(tbs_path, "wb").write(bytes(tbs_bytes))
# openssl 3.5 rejects `dgst -sign K -in F` ("Can only sign or verify one file"):
# the input file is positional.
proc = subprocess.run([openssl, "dgst", "-sha256", "-sign", key, "-out", sig_path, tbs_path],
                      capture_output=True)
if proc.returncode != 0:
    sys.stderr.write(proc.stderr.decode("utf-8", "replace"))
    raise SystemExit("mkocsp: signing the re-dated tbsResponseData failed")
signature = open(sig_path, "rb").read()
basic_new = wrap(0x30, bytes(tbs_bytes) + algid_tlv + wrap(0x03, b"\x00" + signature) + certs_tlv)
open(dst, "wb").write(
    wrap(0x30, enum_tlv + wrap(0xA0, wrap(0x30, oid_tlv + wrap(0x04, basic_new)))))
print("  re-dated %d field(s) to thisUpdate %s .. nextUpdate %s" % (moved, thisupdate, nextupdate))
PY
}

pem() { # $1: in DER, $2: out PEM — openssl writes OCSP responses as DER only
	{ printf -- '-----BEGIN OCSP RESPONSE-----\n'
	  "$OPENSSL" base64 -in "$1"
	  printf -- '-----END OCSP RESPONSE-----\n'; } >"$2"
}

# ── the arms ─────────────────────────────────────────────────────────────────
# good for the sealer (signerA, serial 0A11)
index "$work/index-good.txt" V signerA 0A11
request "$work/req-signerA.der" signerA
respond "$work/index-good.txt" "$work/req-signerA.der" ocsp-responder "$work/good.der"
redate "$work/good.der" "$pki/ocsp-signerA-good.der" ocsp-responder "$NB_2020" "$NA_2099" "$NB_2020"
pem "$pki/ocsp-signerA-good.der" "$pki/ocsp-signerA-good.pem"

# the SAME response with the sealer's serial revoked, 2021-06-01, keyCompromise —
# the same entry the CRL arm carries (tools/mkcrl.sh), one medium over
index "$work/index-revoked.txt" R signerA 0A11
respond "$work/index-revoked.txt" "$work/req-signerA.der" ocsp-responder "$work/revoked.der"
redate "$work/revoked.der" "$pki/ocsp-signerA-revoked.der" ocsp-responder "$NB_2020" "$NA_2099" "$NB_2020"

# the same statement with a window that ended in 2021: expired on any host, at
# any time, exactly as crl-intermediateA-expired.pem is
respond "$work/index-good.txt" "$work/req-signerA.der" ocsp-responder "$work/expired.der"
redate "$work/expired.der" "$pki/ocsp-signerA-expired.der" ocsp-responder "$NB_2020" "$NA_2021" "$NB_2020"

# the same answer from a responder that chains to NOTHING: a self-signed
# certificate, so the answer is signed by a party no supplied anchor vouches for
respond "$work/index-good.txt" "$work/req-signerA.der" ocsp-rogue "$work/rogue.der"
redate "$work/rogue.der" "$pki/ocsp-signerA-rogue.der" ocsp-rogue "$NB_2020" "$NA_2099" "$NB_2020"

# a well-formed answer about a certificate that is NOT in the vectors' chain
# (signerC, serial 0A14): it establishes nothing about the sealed package
index "$work/index-signerC.txt" V signerC 0A14
request "$work/req-signerC.der" signerC
respond "$work/index-signerC.txt" "$work/req-signerC.der" ocsp-responder "$work/signerC.der"
redate "$work/signerC.der" "$pki/ocsp-signerC-good.der" ocsp-responder "$NB_2020" "$NA_2099" "$NB_2020"

chmod 644 "$pki"/ocsp-*.der "$pki"/ocsp-*.pem

printf 'mkocsp.sh: built the OCSP responses under %s\n' "$pki"
for f in signerA-good signerA-revoked signerA-expired signerA-rogue signerC-good; do
	printf '  %-16s %s\n' "$f" \
		"$("$OPENSSL" ocsp -respin "$pki/ocsp-$f.der" -resp_text -no_nonce 2>/dev/null |
			grep -E 'Cert Status|This Update|Next Update|Serial Number' |
			tr -s ' ' | tr '\n' ' ' | sed 's/  */ /g')"
done
